create table public.responsibilities (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.maps(company_id) on delete cascade,
  position bigint generated by default as identity,
  title text not null check (length(btrim(title)) between 1 and 160),
  owner_key text not null default '',
  owner_label text not null default '',
  next_key text not null default '',
  next_label text not null default '',
  hours numeric(5,2) not null default 0 check (hours between 0 and 168),
  target_date date,
  notes text not null default '' check (length(notes)<=3000),
  status text not null default 'To plan' check (status in ('To plan','Ready','Handed off')),
  completed_on date,
  archived boolean not null default false,
  check ((status = 'Handed off') = (completed_on is not null)),
  check (status <> 'Handed off' or (owner_key <> '' and owner_key = next_key))
);
create index responsibilities_order on public.responsibilities(company_id,position,id);

create table public.scenarios (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.maps(company_id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 120),
  goal text not null default '' check (length(goal)<=3000),
  target_date date,
  budget numeric(14,2) check (budget >= 0),
  budget_currency text not null default 'USD' check (budget_currency ~ '^[A-Z]{3}$'),
  is_baseline boolean not null default false,
  archived boolean not null default false,
  created_at timestamptz not null default now(),
  unique(company_id,id)
);
create unique index scenarios_one_baseline on public.scenarios(company_id) where is_baseline;

create table public.scenario_roles (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null,
  scenario_id uuid not null,
  source_placement uuid,
  title text not null check (length(btrim(title)) between 1 and 120),
  assignee text not null default '' check (length(assignee)<=260),
  seniority text not null default '',
  country text not null default '',
  region text not null default '',
  employment text not null default 'Employee' check (employment in ('Employee','Fractional','Contractor')),
  allocation numeric(5,2) not null default 100 check (allocation between 0 and 100),
  period text not null default 'Yearly' check (period in ('Monthly','Yearly')),
  currency text not null default 'USD' check (currency ~ '^[A-Z]{3}$'),
  cost_low numeric(14,2) check (cost_low >= 0),
  cost_high numeric(14,2) check (cost_high is null or (cost_low is not null and cost_high >= cost_low)),
  basis text not null default 'Employer cost' check (basis in ('Base pay','Employer cost','Contractor fee')),
  burden numeric(5,2) check (burden is null or (burden >= 0 and basis = 'Base pay')),
  full_time boolean not null default true,
  source text not null default '',
  estimate_date date,
  archived boolean not null default false,
  foreign key (company_id,scenario_id) references public.scenarios(company_id,id) on delete cascade
);
create index scenario_roles_scope on public.scenario_roles(company_id,scenario_id);

do $$
declare t text;
begin
  foreach t in array array['responsibilities','scenarios','scenario_roles'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from public,anon,authenticated', t);
    execute format('grant select,insert on public.%I to authenticated', t);
    execute format('create policy workspace_only on public.%I for all to authenticated using ((select public.has_workspace_access(company_id))) with check ((select public.has_workspace_access(company_id)))', t);
  end loop;
end $$;

grant update (position,title,owner_key,owner_label,next_key,next_label,hours,target_date,notes,status,completed_on,archived) on public.responsibilities to authenticated;
grant update (name,goal,target_date,budget,budget_currency,archived) on public.scenarios to authenticated;
grant update (title,assignee,seniority,country,region,employment,allocation,period,currency,cost_low,cost_high,basis,burden,full_time,source,estimate_date,archived) on public.scenario_roles to authenticated;

create function public.move_responsibility(workspace uuid, item uuid, anchor uuid, after_anchor boolean) returns void
language plpgsql security invoker set search_path = '' as $$
begin
  if not public.has_workspace_access(workspace) then raise insufficient_privilege; end if;
  perform pg_advisory_xact_lock(hashtextextended(workspace::text, 817));
  if item = anchor or (select count(*) from public.responsibilities
      where company_id=workspace and id in (item,anchor) and not archived) <> 2 then return; end if;
  with ordered as (
    select r.id, row_number() over (order by
      case when r.id=item then a.position else r.position end,
      case when r.id=item then case when after_anchor then 1 else -1 end else 0 end,r.id) as pos
    from public.responsibilities r
    join public.responsibilities a on a.company_id=r.company_id and a.id=anchor
    where r.company_id=workspace and not r.archived
  )
  update public.responsibilities r set position=o.pos from ordered o
  where r.company_id=workspace and r.id=o.id;
end $$;

create function public.snapshot_scenario(workspace uuid, plan_name text, baseline boolean) returns uuid
language plpgsql security invoker set search_path = '' as $$
declare plan uuid;
begin
  if not public.has_workspace_access(workspace) then raise insufficient_privilege; end if;
  perform pg_advisory_xact_lock(hashtextextended(workspace::text, 818));
  if baseline then
    select id into plan from public.scenarios where company_id=workspace and is_baseline;
    if found then return plan; end if;
  end if;
  insert into public.scenarios(company_id,name,is_baseline) values(workspace,btrim(plan_name),baseline)
    returning id into plan;
  insert into public.scenario_roles(company_id,scenario_id,source_placement,title,assignee,
    seniority,country,region,employment,allocation,period,currency,cost_low,cost_high,basis,burden,full_time,source,estimate_date)
  select workspace,plan,p.id,p.title,concat_ws(' · ',person.name,org.name),
    coalesce(c.seniority,''),coalesce(c.country,''),coalesce(c.region,''),coalesce(c.employment,'Employee'),
    coalesce(c.allocation,100),coalesce(c.period,'Yearly'),coalesce(c.currency,'USD'),c.cost_low,c.cost_high,
    coalesce(c.basis,'Employer cost'),c.burden,coalesce(c.full_time,true),coalesce(c.source,''),c.estimate_date
  from public.placements p
  left join public.people person on person.company_id=workspace and person.id=p.person_id
  left join public.organizations org on org.company_id=workspace and org.id=p.organization_id
  left join public.scenarios b on b.company_id=workspace and b.is_baseline
  left join lateral (
    select r.* from public.scenario_roles r where r.company_id=workspace and r.scenario_id=b.id
      and r.source_placement=p.id and not r.archived and not baseline order by r.id limit 1
  ) c on true
  where p.company_id=workspace and (not baseline or p.status='Filled');
  return plan;
end $$;

revoke all on function public.snapshot_scenario(uuid,text,boolean), public.move_responsibility(uuid,uuid,uuid,boolean) from public,anon;
grant execute on function public.snapshot_scenario(uuid,text,boolean), public.move_responsibility(uuid,uuid,uuid,boolean) to authenticated;
